import { deepStrictEqual } from "node:assert";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { values: { check = false, cli } } = parseArgs({
	options: { check: { type: "boolean" }, cli: { type: "string" } },
});

const interfaces = [
	["dev.dbgjs.cdp-debugger", "ServiceApi"],
	["dev.dbgjs.context", "ContextApi"],
	["dev.dbgjs.source", "SourceApi"],
	["dev.dbgjs.capture", "CaptureApi"],
	["dev.dbgjs.target-debugger", "TargetDebuggerApi"],
	["dev.dbgjs.cdp-access", "CdpAccessApi"],
	["dev.dbgjs.relay", "RelayApi"],
	["dev.dbgjs.browser-automation", "BrowserAutomationApi"],
	["dev.dbgjs.coverage", "CoverageApi"],
	["dev.dbgjs.cpu-profiler", "CpuProfilerApi"],
	["dev.dbgjs.heap-profiler", "HeapProfilerApi"],
];
const generatedHeader = "// @generated by npm run generate:contracts. DO NOT EDIT.\n";
const outputDirectory = resolve(repositoryRoot, "vscode-extension/src/generated");
const filenames = ["interfaces.ts"];
deepStrictEqual(
	existsSync(outputDirectory)
		? readdirSync(outputDirectory).filter(name => name.endsWith(".ts") && !filenames.includes(name))
		: [],
	[],
	"Remove obsolete generated daemon modules that are not in the capability catalog",
);
if (!check) {
	mkdirSync(outputDirectory, { recursive: true });
}

const linkrpc = cli === undefined ? installedCli() : resolve(cli);
if (!existsSync(linkrpc)) {
	throw new Error(`The installed LinkRPC CLI is missing at ${linkrpc}. Restore dependencies or build the linked CLI.`);
}

run("cargo", ["build", "--locked", "--bin", "dbgjs-service"]);
const metadata = JSON.parse(capture("cargo", ["metadata", "--locked", "--no-deps", "--format-version", "1"]));
const executable = join(metadata.target_directory, "debug", `dbgjs-service${process.platform === "win32" ? ".exe" : ""}`);
const endpoint = new URL("cmd-stdio:");
endpoint.searchParams.append("argv", executable);
endpoint.searchParams.append("argv", "--stdio");

const temporaryDirectory = mkdtempSync(join(tmpdir(), "dbgjs-contracts-"));
try {
	const bundlePath = join(temporaryDirectory, "daemon.json");
	run(process.execPath, [
		linkrpc, "--context", ":empty", "--no-use-env", "--endpoint", endpoint.href,
		"contract", "export", "--output", bundlePath,
	]);
	const bundle = JSON.parse(readFileSync(bundlePath, "utf8"));
	const reflected = bundle.interfaceSchemas
		.filter(schema => schema.id.startsWith("dev.dbgjs."))
		.map(schema => schema.id).sort();
	deepStrictEqual(
		reflected,
		interfaces.map(([id]) => id).sort(),
		"TypeScript generation must cover every reflected daemon interface exactly once",
	);

	const interfaceNames = {};
	const bindingNames = {};
	for (const [id, name] of interfaces) {
		const schemas = bundle.interfaceSchemas.filter(schema => schema.id === id);
		deepStrictEqual(schemas.length, 1, `Expected exactly one schema for ${id}`);
		const key = `${id}@${schemas[0].hash}`;
		interfaceNames[key] = name;
		bindingNames[`root:${key}`] = `${name}Root`;
	}
	const namesPath = join(temporaryDirectory, "names.json");
	writeFileSync(namesPath, JSON.stringify({ interfaceNames, bindingNames }));
	const temporaryOutput = join(temporaryDirectory, "interfaces.ts");
	run(process.execPath, [
		linkrpc, "codegen", "--input", bundlePath, "--names", namesPath,
		"--output", temporaryOutput,
	]);
	const generated = generatedHeader + readFileSync(temporaryOutput, "utf8");
	const output = join(outputDirectory, "interfaces.ts");
	if (check) {
		if (!existsSync(output) || readFileSync(output, "utf8") !== generated) {
			throw new Error(`${output} is stale or missing; run npm run generate:contracts`);
		}
	} else {
		writeFileSync(output, generated);
	}
} finally {
	rmSync(temporaryDirectory, { recursive: true });
}

function installedCli() {
	const require = createRequire(import.meta.url);
	const packagePath = require.resolve("@hediet/linkrpc-cli/package.json");
	const { bin } = JSON.parse(readFileSync(packagePath, "utf8"));
	const cliEntry = typeof bin === "string" ? bin : bin?.linkrpc;
	if (typeof cliEntry !== "string") {
		throw new Error("The installed @hediet/linkrpc-cli package does not declare a linkrpc executable");
	}
	return resolve(dirname(packagePath), cliEntry);
}

function run(command, args) {
	execute(command, args, "inherit");
}

function capture(command, args) {
	return execute(command, args, ["ignore", "pipe", "inherit"]).stdout;
}

function execute(command, args, stdio) {
	const result = spawnSync(command, args, {
		cwd: repositoryRoot,
		stdio,
		encoding: "utf8",
	});
	if (result.error) {
		throw result.error;
	}
	if (result.status !== 0) {
		throw new Error(`${command} ${args.join(" ")} failed (${result.signal ?? result.status})`);
	}
	return result;
}
