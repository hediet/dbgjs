use std::fs;
use std::path::PathBuf;

use dbgjs::protocol_schema::import_typed_cdp_protocol;
use hubrpc::prelude::{GenerateRustOptions, generate_rust_interface};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let repository_root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let schema_root = repository_root
        .join("node_modules")
        .join("devtools-protocol")
        .join("json");
    let browser_protocol = fs::read_to_string(schema_root.join("browser_protocol.json"))?;
    let js_protocol = fs::read_to_string(schema_root.join("js_protocol.json"))?;
    let interface = import_typed_cdp_protocol(&browser_protocol, &js_protocol)?;
    let method_count = interface.methods.len();
    let type_count = interface
        .components
        .as_ref()
        .and_then(|components| components.schemas.as_ref())
        .map_or(0, |schemas| schemas.len());
    let generated = generate_rust_interface(
        &interface,
        &GenerateRustOptions {
            client_name: Some("CdpClient".into()),
            ..GenerateRustOptions::default()
        },
    );
    let output_dir = repository_root.join("target").join("cdp-codegen");
    fs::create_dir_all(&output_dir)?;
    fs::write(output_dir.join("cdp.rs"), &generated.code)?;
    fs::write(
        output_dir.join("cdp.protocol.json"),
        serde_json::to_vec_pretty(&interface)?,
    )?;

    println!("interface: {}", interface.id_at_hash());
    println!("methods: {method_count}");
    println!("component schemas: {type_count}");
    println!("generated bytes: {}", generated.code.len());
    println!("unsupported constructs: {}", generated.unsupported.len());
    for unsupported in generated.unsupported.iter().take(20) {
        println!("- {unsupported}");
    }
    println!("output: {}", output_dir.display());
    Ok(())
}
